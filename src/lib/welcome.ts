/** 与欢迎语同一行的时问候；早上、下午、晚上都有本地化文案。 */
export function greetingLine(): string {
  const hour = new Date().getHours();
  if (hour >= 5 && hour < 12) return t("上午好，");
  if (hour >= 12 && hour < 18) return t("下午好，");
  return t("晚上好，");
}

export function pickWelcome(): string {
  const index = Math.floor(Math.random() * WELCOME_LINES.length);
  const lang = getUiLanguage();
  if (lang === "zh") return WELCOME_LINES[index];
  if (lang === "en") return WELCOME_EN[index] ?? WELCOME_LINES[index];
  if (lang === "ja" || lang === "ko") return WELCOME_LINES[index];
  const pool = WELCOME_MORE[lang];
  if (pool?.length) return pool[Math.floor(Math.random() * pool.length)];
  return WELCOME_LINES[index];
}

const FIRST_RUN_KEY = "chapter.firstRun";
const ONE_DAY = 86400000;

export function companionDays(): number {
  const today = new Date();
  const todayKey = `${today.getFullYear()}-${String(today.getMonth() + 1).padStart(2, "0")}-${String(
    today.getDate(),
  ).padStart(2, "0")}`;
  let first = "";
  try {
    first = localStorage.getItem(FIRST_RUN_KEY) ?? "";
    if (!first) {
      localStorage.setItem(FIRST_RUN_KEY, todayKey);
      first = todayKey;
    }
  } catch {
    first = todayKey;
  }
  const start = new Date(`${first}T00:00:00`).getTime();
  if (!Number.isFinite(start)) return 1;
  const now = new Date(today.getFullYear(), today.getMonth(), today.getDate()).getTime();
  return Math.max(1, Math.floor((now - start) / ONE_DAY) + 1);
}
